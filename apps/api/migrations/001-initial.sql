CREATE TABLE employees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
  role TEXT NOT NULL CHECK (role IN ('sales','inventory','manager','admin')),
  salt TEXT NOT NULL, password_hash TEXT NOT NULL
);
CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES employees(id), expires_at BIGINT NOT NULL
);
CREATE TABLE branches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE, address TEXT NOT NULL
);
CREATE TABLE vehicle_models (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand TEXT NOT NULL, name TEXT NOT NULL, variant TEXT NOT NULL,
  fuel TEXT NOT NULL, transmission TEXT NOT NULL,
  base_price BIGINT NOT NULL CHECK (base_price > 0), created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vin TEXT NOT NULL UNIQUE, model_id BIGINT NOT NULL REFERENCES vehicle_models(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id), color TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('available','reserved','in_transit','sold')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, phone TEXT NOT NULL, email TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '', created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers(id),
  vehicle_id BIGINT NOT NULL REFERENCES vehicles(id), employee_id BIGINT NOT NULL REFERENCES employees(id),
  status TEXT NOT NULL CHECK (status IN ('confirmed','converted','cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX active_booking_vin ON bookings(vehicle_id) WHERE status IN ('confirmed','converted');
CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(id),
  base_price BIGINT NOT NULL CHECK (base_price > 0), extras BIGINT NOT NULL CHECK (extras >= 0),
  tax BIGINT NOT NULL CHECK (tax >= 0), total BIGINT NOT NULL CHECK (total = base_price + extras + tax),
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','delivered')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), delivered_at TIMESTAMPTZ,
  delivered_by BIGINT REFERENCES employees(id)
);
CREATE TABLE invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id), reference TEXT NOT NULL UNIQUE,
  amount BIGINT NOT NULL CHECK (amount > 0), created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE payment_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id), amount BIGINT NOT NULL CHECK (amount > 0),
  status TEXT NOT NULL CHECK (status IN ('pending','paid','cancelled')), note TEXT NOT NULL DEFAULT '',
  created_by BIGINT NOT NULL REFERENCES employees(id), settled_by BIGINT REFERENCES employees(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), settled_at TIMESTAMPTZ, cancelled_at TIMESTAMPTZ
);
CREATE TABLE documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  type TEXT NOT NULL CHECK (type IN ('identity','address','insurance','registration')),
  filename TEXT NOT NULL, storage_name TEXT NOT NULL UNIQUE, mime TEXT NOT NULL,
  size BIGINT NOT NULL CHECK (size > 0 AND size <= 4194304),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','verified','rejected')),
  note TEXT NOT NULL DEFAULT '', uploaded_by BIGINT NOT NULL REFERENCES employees(id),
  reviewed_by BIGINT REFERENCES employees(id), reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX vehicles_model ON vehicles(model_id);
CREATE INDEX vehicles_branch_status ON vehicles(branch_id,status);
CREATE INDEX bookings_customer ON bookings(customer_id);
CREATE INDEX bookings_status ON bookings(status);
CREATE INDEX payments_order_status ON payment_requests(order_id,status);
CREATE INDEX documents_order_type ON documents(order_id,type);
CREATE INDEX sessions_expiry ON sessions(expires_at);
CREATE TABLE data_imports (
  source_checksum TEXT PRIMARY KEY,
  report JSONB NOT NULL,
  imported_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
